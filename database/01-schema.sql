\set ON_ERROR_STOP on
BEGIN;
SELECT pg_advisory_xact_lock(1983170262, 1);

CREATE TABLE IF NOT EXISTS motorista (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    nome VARCHAR(100) NOT NULL CHECK (btrim(nome) <> ''),
    cpf VARCHAR(11) NOT NULL CONSTRAINT uq_motorista_cpf UNIQUE CHECK (cpf ~ '^[0-9]{11}$'),
    cnh VARCHAR(11) NOT NULL CONSTRAINT uq_motorista_cnh UNIQUE CHECK (cnh ~ '^[0-9]{11}$'),
    categoria_cnh VARCHAR(2) NOT NULL CHECK (categoria_cnh IN ('A','B','AB','C','D','E','AC','AD','AE')),
    telefone VARCHAR(20) NOT NULL CHECK (btrim(telefone) <> ''),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS veiculo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    placa VARCHAR(7) NOT NULL CONSTRAINT uq_veiculo_placa UNIQUE CHECK (placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    modelo VARCHAR(100) NOT NULL CHECK (btrim(modelo) <> ''),
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1900 AND 2100),
    capacidade_kg DECIMAL(10,2) NOT NULL CHECK (capacidade_kg > 0 AND capacidade_kg <> 'NaN'::numeric),
    status VARCHAR(20) NOT NULL DEFAULT 'Disponível' CHECK (status IN ('Disponível','Em viagem','Em manutenção'))
);

CREATE TABLE IF NOT EXISTS cliente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    nome VARCHAR(100) NOT NULL CHECK (btrim(nome) <> ''),
    cpf_cnpj VARCHAR(14) NOT NULL CONSTRAINT uq_cliente_cpf_cnpj UNIQUE CHECK (cpf_cnpj ~ '^([0-9]{11}|[0-9]{14})$'),
    telefone VARCHAR(20) NOT NULL CHECK (btrim(telefone) <> ''),
    endereco VARCHAR(200) NOT NULL CHECK (btrim(endereco) <> '')
);

CREATE TABLE IF NOT EXISTS viagem (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    motorista_id INTEGER NOT NULL REFERENCES motorista(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    veiculo_id INTEGER NOT NULL REFERENCES veiculo(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    cliente_id INTEGER NOT NULL REFERENCES cliente(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    origem VARCHAR(100) NOT NULL CHECK (btrim(origem) <> ''),
    destino VARCHAR(100) NOT NULL CHECK (btrim(destino) <> ''),
    data_saida DATE NOT NULL,
    data_chegada DATE,
    valor_frete DECIMAL(10,2) NOT NULL CHECK (valor_frete > 0 AND valor_frete <> 'NaN'::numeric),
    status VARCHAR(20) NOT NULL DEFAULT 'Planejada' CHECK (status IN ('Planejada','Em andamento','Concluída','Cancelada')),
    CONSTRAINT ck_viagem_datas CHECK (data_chegada IS NULL OR data_chegada >= data_saida),
    CONSTRAINT ck_viagem_concluida CHECK (status <> 'Concluída' OR data_chegada IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS manutencao (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    veiculo_id INTEGER NOT NULL REFERENCES veiculo(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    data DATE NOT NULL,
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('Preventiva','Corretiva')),
    descricao VARCHAR(255) NOT NULL CHECK (btrim(descricao) <> ''),
    custo DECIMAL(10,2) NOT NULL CHECK (custo >= 0 AND custo <> 'NaN'::numeric),
    quilometragem INTEGER NOT NULL CHECK (quilometragem >= 0)
);

CREATE INDEX IF NOT EXISTS ix_viagem_motorista ON viagem(motorista_id);
CREATE INDEX IF NOT EXISTS ix_viagem_veiculo ON viagem(veiculo_id);
CREATE INDEX IF NOT EXISTS ix_viagem_cliente_saida ON viagem(cliente_id, data_saida);
CREATE INDEX IF NOT EXISTS ix_viagem_saida ON viagem(data_saida);
CREATE INDEX IF NOT EXISTS ix_manutencao_veiculo_data ON manutencao(veiculo_id, data);
CREATE UNIQUE INDEX IF NOT EXISTS uq_viagem_motorista_andamento ON viagem(motorista_id) WHERE status = 'Em andamento';
CREATE UNIQUE INDEX IF NOT EXISTS uq_viagem_veiculo_andamento ON viagem(veiculo_id) WHERE status = 'Em andamento';

COMMIT;
